# Scans /assets and writes /database/media.js — the list of files in every folder.
# Grid blocks with `folder:` read from this list, so new images show up automatically.
# Run it (double-click scan-media.bat) whenever you add, rename or delete media.

$root   = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$assets = Join-Path $root 'assets'
$out    = Join-Path $root 'database\media.js'
$exts   = @('.png', '.jpg', '.jpeg', '.webp', '.gif', '.svg', '.avif', '.mp4', '.webm', '.mov', '.m4v')

$map = [ordered]@{}
Get-ChildItem -LiteralPath $assets -Recurse -File |
  Where-Object { $exts -contains $_.Extension.ToLower() -and $_.Name -notlike '._*' } |
  Sort-Object FullName |
  ForEach-Object {
    $rel = $_.DirectoryName.Substring($assets.Length).TrimStart('\').Replace('\', '/')
    if (-not $map.Contains($rel)) { $map[$rel] = New-Object System.Collections.ArrayList }
    [void]$map[$rel].Add($_.Name)
  }

function Quote([string]$s) { '"' + $s.Replace('\', '\\').Replace('"', '\"') + '"' }

$lines = foreach ($k in $map.Keys) {
  "  $(Quote $k): [$((($map[$k] | ForEach-Object { Quote $_ }) -join ', '))],"
}
$js = "/* AUTO-GENERATED by code/tools/scan-media - do not edit by hand. */`nPOSHA.media = {`n$($lines -join "`n")`n};`n"
[IO.File]::WriteAllText($out, $js, (New-Object Text.UTF8Encoding $false))

$count = ($map.Values | ForEach-Object { $_.Count } | Measure-Object -Sum).Sum
Write-Host "Indexed $([int]$count) files in $($map.Count) folders -> database/media.js"
